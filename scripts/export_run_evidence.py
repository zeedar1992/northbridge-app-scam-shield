#!/usr/bin/env python3
"""Export a Lakeflow Job run as TEXT evidence: every notebook task's executed code + real outputs -> Markdown.

Usage: python3 scripts/export_run_evidence.py <job_run_id> [--profile PROFILE] [--out evidence/job_run]
Writes one <task_key>.md per notebook task, plus run_summary.md (task states, durations, pipeline update).
"""
import argparse
import base64
import json
import pathlib
import re
import subprocess
import urllib.parse
from datetime import datetime, timezone

ANSI = re.compile(r"\x1b\[[0-9;]*m")


def cli(args, profile):
    out = subprocess.run(["databricks", *args, "--profile", profile, "-o", "json"], capture_output=True, text=True, check=True)
    return json.loads(out.stdout)


def notebook_model(html: str) -> dict:
    m = re.search(r"__DATABRICKS_NOTEBOOK_MODEL = '([^']+)'", html)
    return json.loads(urllib.parse.unquote(base64.b64decode(m.group(1)).decode()))


def md_table(res: dict, max_rows: int = 40) -> str:
    cols = [c["name"] for c in res.get("schema", [])]
    rows = res.get("data", [])
    if not cols:
        return ""
    fmt = lambda v: str(v).replace("|", "\\|").replace("\n", " ")[:220]  # noqa: E731
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows[:max_rows]]
    if len(rows) > max_rows:
        lines.append(f"\n_… {len(rows) - max_rows} more rows truncated_")
    return "\n".join(lines)


def render_results(r: dict | None) -> str:
    if not r:
        return ""
    parts = []
    items = r.get("data") if r.get("type") == "listResults" else [r]
    for it in items or []:
        t = it.get("type")
        if t == "table":
            parts.append(md_table(it))
        elif t in ("ansi", "text"):
            txt = ANSI.sub("", str(it.get("data", ""))).rstrip()
            if txt:
                parts.append("```text\n" + txt[:12000] + "\n```")
        elif t == "html":
            txt = re.sub(r"<[^>]+>", " ", str(it.get("data", "")))
            txt = re.sub(r"\s+", " ", txt).strip()
            if txt:
                parts.append("```text\n" + txt[:4000] + "\n```")
        elif t == "error":
            parts.append("```text\nERROR: " + ANSI.sub("", str(it.get("data", "")))[:4000] + "\n```")
    if r.get("type") == "error" or r.get("errorSummary"):
        parts.append("```text\nERROR: " + ANSI.sub("", str(r.get("errorSummary") or r.get("data")))[:4000] + "\n```")
    return "\n\n".join(p for p in parts if p)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run_id")
    ap.add_argument("--profile", default="fevm-serverless-stable-my49a8")
    ap.add_argument("--out", default="evidence/job_run")
    a = ap.parse_args()
    out = pathlib.Path(a.out); out.mkdir(parents=True, exist_ok=True)
    run = cli(["jobs", "get-run", a.run_id], a.profile)
    ts = lambda ms: datetime.fromtimestamp(ms / 1000, timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC") if ms else "-"  # noqa: E731
    summary = [f"# Job run {a.run_id}: {run.get('run_name')}", "",
               f"* Result: **{run['state'].get('result_state')}**  ·  start {ts(run.get('start_time'))}  ·  end {ts(run.get('end_time'))}",
               f"* Run page: {run.get('run_page_url')}", "", "| task | result | duration (s) | start (UTC) |", "|---|---|---|---|"]
    for t in sorted(run["tasks"], key=lambda t: t.get("start_time", 0)):
        dur = round((t.get("end_time", 0) - t.get("start_time", 0)) / 1000) if t.get("end_time") else "-"
        summary.append(f"| {t['task_key']} | {t['state'].get('result_state', t['state'].get('life_cycle_state'))} | {dur} | {ts(t.get('start_time'))} |")
        if "notebook_task" not in t:
            continue
        try:
            exp = cli(["jobs", "export-run", str(t["run_id"]), "--views-to-export", "CODE"], a.profile)
            model = notebook_model(exp["views"][0]["content"])
        except Exception as e:  # noqa: BLE001
            print("skip", t["task_key"], e); continue
        md = [f"# Task `{t['task_key']}` · notebook `{model.get('name')}`", "",
              f"Job run {a.run_id} · task run {t['run_id']} · result **{t['state'].get('result_state')}** · {ts(t.get('start_time'))}",
              "", "> Exported from the executed job run (code + real outputs). Generated by `scripts/export_run_evidence.py`.", ""]
        for c in sorted(model["commands"], key=lambda c: c.get("position", 0)):
            src = c.get("command", "")
            if src.lstrip().startswith("%md"):
                md.append(re.sub(r"^%md\s?", "", src.lstrip()).strip()); md.append("")
                continue
            md.append("```python\n" + src.strip() + "\n```")
            res = render_results(c.get("results"))
            if res:
                md.append("**Output:**\n\n" + res)
            md.append("")
        (out / f"{t['task_key']}.md").write_text("\n".join(md))
        print("wrote", out / f"{t['task_key']}.md")
    (out / "run_summary.md").write_text("\n".join(summary) + "\n")
    print("wrote", out / "run_summary.md")


if __name__ == "__main__":
    main()
